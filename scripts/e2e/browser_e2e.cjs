const { chromium } = require('playwright');
const fs = require('fs');
const S = process.argv[2]; // directory containing stress.csv
fs.mkdirSync(S + '/shots', { recursive: true });
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
  const errors = []; const hosts = new Set();
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('request', r => hosts.add(new URL(r.url()).host));
  await page.goto('http://127.0.0.1:5173/');
  await page.click('text=Sign in');
  await page.click('button:has-text("Create account")');
  const email = `ui${Date.now()}@example.com`;
  await page.fill('#authName', 'UI Tester'); await page.fill('#businessName', 'UI Co');
  await page.fill('#authEmail', email); await page.fill('#authPassword', 'longpassword1'); await page.fill('#authConfirm', 'longpassword1');
  await page.click('button[type=submit]');
  await page.waitForSelector('.side-nav');
  const navLabels = await page.$$eval('.side-nav button', b => b.map(x => x.textContent.trim()));
  console.log('nav:', navLabels);
  await page.click('text=Manage plants');
  await page.fill('#plantName', 'Browser Plant'); await page.click('button:has-text("Register plant")');
  await page.waitForSelector('text=Use for upload');
  await page.click('.side-nav button:has-text("Upload")');
  await page.setInputFiles('#datasetFile', S + '/stress.csv');
  await page.click('button:has-text("Upload and analyse")');
  await page.waitForSelector('.pipeline-stages', { timeout: 5000 });
  await page.waitForSelector('text=Report ready', { timeout: 120000 });
  await page.screenshot({ path: S + '/shots/upload.png', fullPage: false });
  await page.click('button:has-text("Open report")');
  await page.waitForSelector('text=How your columns were interpreted');
  await page.screenshot({ path: S + '/shots/report.png', fullPage: true });
  const kpis = await page.$$eval('.report-metrics article', a => a.map(x => x.innerText.replace(/\n/g, ': ')));
  console.log('kpis:', kpis);
  await page.click('.side-nav button:has-text("AI explanation")');
  await page.fill('.chat-composer textarea', 'Why is measured output below expected energy?');
  await page.keyboard.press('Enter');
  await page.waitForSelector('.chat-followups', { timeout: 60000 });
  await page.click('.chat-followups button >> nth=0');
  await page.waitForFunction(() => document.querySelectorAll('.chat-turn.user').length === 2 && document.querySelectorAll('.chat-followups').length === 1, null, { timeout: 60000 });
  await page.screenshot({ path: S + '/shots/chat.png', fullPage: true });
  console.log('turns:', await page.$$eval('.chat-turn', t => t.map(x => x.className)));
  await page.reload(); await page.waitForSelector('.side-nav');
  await page.click('.side-nav button:has-text("Reports")');
  console.log('reports after reload:', await page.$$eval('.report-picker button', b => b.length));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: S + '/shots/mobile.png' });
  console.log('console errors:', errors); console.log('hosts:', [...hosts]);
  await browser.close();
})().catch(e => { console.error('FAIL', e.message); process.exit(1); });
