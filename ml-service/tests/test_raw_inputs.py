def test_wide_power_columns_become_devices_and_energy_uses_duration(tmp_path):
    times = pd.date_range("2026-03-01 10:00", periods=8, freq="15min", tz="UTC")
    frame = pd.DataFrame({"Time": times.strftime("%Y-%m-%dT%H:%M:%SZ"), "GTI": 800.0,
                          "E_Grid_U7": 40.0, "E_Grid_U8": 20.0, "EArray_U7": 41.0, "EArray_U8": 21.0})
    units = pd.DataFrame([["", "W/m2", "kW", "kW", "kW", "kW"]], columns=frame.columns)
    path = tmp_path / "wide.csv"
    pd.concat([units, frame]).to_csv(path, index=False)
    table = ingest_file(path).tables[0]
    assert table.layout["layout_type"] == "wide"
    assert set(table.layout["devices"]) == {"U7", "U8"}
    result = analyze(path, mode="full")
    devices = {item["device_id"]: item for item in result["device_performance"]}
    assert set(devices) == {"U7", "U8"}
    # 8 x 15-minute intervals of average power: kW x 0.25 h, never summed as kWh.
    assert devices["U7"]["actual_energy_kwh"] == pytest.approx(40.0 * 8 * 0.25)
    assert result["actual_energy"] == pytest.approx(60.0 * 8 * 0.25)


