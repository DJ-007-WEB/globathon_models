def _cusum_frame(actual: list[float]) -> pd.DataFrame:
    times = pd.date_range("2026-03-01T04:00:00Z", periods=len(actual), freq="15min")
    return pd.DataFrame({"timestamp": times, "device_id": "INV", "ac_power_kw": actual,
                         "poa_irradiance_w_m2": 900.0, "rated_ac_power_kw": 100.0})


def _alerts(frame: pd.DataFrame, expected: float = 80.0) -> list[dict]:
    return detect_anomalies(frame, expected_power_kw=pd.Series(expected, index=frame.index),
                            actual_column="ac_power_kw", device_column="device_id",
                            timestamp_column="timestamp", poa_column="poa_irradiance_w_m2",
                            capacity_column="rated_ac_power_kw")["alerts"]


def test_cusum_recovers_after_a_shortfall_and_never_alerts_when_output_is_at_or_above_expected():
    assert _alerts(_cusum_frame([80.0] * 20 + [90.0] * 20)) == []
    alerts = _alerts(_cusum_frame([80.0] * 4 + [0.0] * 8 + [85.0] * 30))
    times = [pd.Timestamp(item["timestamp_utc"]) for item in alerts]
    assert times and max(times) < pd.Timestamp("2026-03-01T07:00:00Z")  # stops once output recovers


def test_cusum_is_not_carried_across_missing_intervals():
    frame = _cusum_frame([60.0] * 5 + [60.0] * 5)
    # A two-hour data gap between the two halves.
    frame.loc[5:, "timestamp"] = frame.loc[5:, "timestamp"] + pd.Timedelta(hours=2)
    scores = detect_anomalies(frame, expected_power_kw=pd.Series(80.0, index=frame.index),
                              actual_column="ac_power_kw", device_column="device_id",
                              timestamp_column="timestamp", poa_column="poa_irradiance_w_m2",
                              capacity_column="rated_ac_power_kw")["assessments"]["cusum_score"]
    assert scores.iloc[5] < scores.iloc[4]


