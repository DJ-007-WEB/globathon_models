def test_hypothesis_cap_keeps_event_attributed_hypotheses_and_reports_truncation():
    from src.config import load_defaults
    from src.service import _attribution

    config = load_defaults()
    config["integration"]["max_hypotheses"] = 3
    times = pd.date_range("2026-03-01T05:00:00Z", periods=10, freq="15min")
    alerts = [{"timestamp_utc": t.isoformat(), "device_id": "INV", "status": "suspected",
               "checks": ["residual_shortfall"],
               "evidence": {"actual_power_kw": 0.0, "expected_power_kw": 80.0, "poa_irradiance_w_m2": 900.0}}
              for t in times]
    events = pd.DataFrame({"start_utc": [times[-2]], "end_utc": [times[-1]], "event_type": ["inverter_trip"],
                           "asset_id": ["INV"], "description": [""]})
    hypotheses, _, limitations = _attribution(alerts, event_log=events, config=config)
    assert len(hypotheses) == 3
    assert sum(item["cause"] == "logged_outage_or_curtailment" for item in hypotheses) == 2
    assert any("Hypotheses truncated: 3 of" in item for item in limitations)


