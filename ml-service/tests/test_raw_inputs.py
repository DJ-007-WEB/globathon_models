def test_date_order_uses_whole_column_and_keeps_true_ambiguity():
    ambiguous_first = [f"{day:02d}-03-2026 10:00" for day in range(1, 13) for _ in range(60)]
    later = [f"{day:02d}-03-2026 10:00" for day in range(13, 32)]
