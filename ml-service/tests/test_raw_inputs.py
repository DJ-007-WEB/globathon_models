def test_design_forecast_power_maps_and_hourly_energy_is_not_undercounted(tmp_path):
    hours = pd.date_range("2026-03-01 00:00", periods=48, freq="1h", tz="UTC")
    forecast = pd.DataFrame({"timestamp": hours.strftime("%Y-%m-%dT%H:%M:%SZ"), "design_expected_ac_kw": 100.0})
    quarter = pd.date_range("2026-03-01 00:00", periods=48 * 4, freq="15min", tz="UTC")
    operating = pd.DataFrame({"timestamp_utc": quarter.strftime("%Y-%m-%dT%H:%M:%SZ"), "ac_power_kw": 50.0})
    result = analyze({"operating_data": operating, "forecast_data": forecast}, mode="full")
    validate_contract(result)
    assert result["energy"]["forecast"]["status"] == "available"
    # 48 hourly rows x 100 kW x 1 h, not x 0.25 h.
    assert result["forecast_energy"] == pytest.approx(4800.0)
    assert result["actual_energy"] == pytest.approx(48 * 50.0)


